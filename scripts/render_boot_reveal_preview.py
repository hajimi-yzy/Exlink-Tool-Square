"""Python-only design preview, not an LVGL or hardware validation.

Uses the real boot portraits/wordmark and a five-character Chinese caption.
The original wordmark is raster artwork, not a font. Microsoft YaHei Bold
is used as an explicit visual substitute at the same visible letter height.
Firmware artwork is generated only when --write-assets is explicitly supplied.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import re

from PIL import Image, ImageDraw, ImageFont


def asset(source: str, name: str, *, monochrome: bool = True) -> Image.Image:
    pixels = re.search(re.escape(name + "_data[]") + r" *= *[{](.*?)[}];", source, re.S)
    descriptor = re.search(r"const lv_img_dsc_t " + re.escape(name) + r" *= *[{](.*?)[}];", source, re.S)
    if not pixels or not descriptor:
        raise ValueError(f"Production image missing: {name}")
    width = int(re.search(r"[.]header[.]w *= *([0-9]+)", descriptor[1])[1])
    height = int(re.search(r"[.]header[.]h *= *([0-9]+)", descriptor[1])[1])
    data = bytes(int(value, 16) for value in re.findall(r"0x([0-9a-fA-F]{2})", pixels[1]))
    assert len(data) == width * height * 3
    pixels = bytearray()
    for i in range(0, len(data), 3):
        value = data[i] | (data[i + 1] << 8)
        r, g, b = (value >> 11) & 31, (value >> 5) & 63, value & 31
        if monochrome:
            # White portrait coverage remains identical to the approved A8 asset.
            level = max((r * 255 + 15) // 31, (g * 255 + 31) // 63, (b * 255 + 15) // 31)
            pixels.append((level * data[i + 2] + 127) // 255)
        else:
            # Preserve the original RGB565 wordmark, including red Exlink and
            # white TOOL. Match LVGL 8.2's RGB565 alpha-over-black arithmetic
            # and lv_color_to32 channel expansion instead of inventing a red.
            alpha = data[i + 2]
            if alpha != 255:
                foreground = (value | (value << 16)) & 0x07E0F81F
                packed = ((foreground * ((alpha + 4) >> 3)) >> 5) & 0x07E0F81F
                value = ((packed >> 16) | packed) & 0xFFFF
            pixels.extend((((value >> 11) * 263 + 7) >> 5,
                           (((value >> 5) & 63) * 259 + 3) >> 6,
                           ((value & 31) * 263 + 7) >> 5))
    return Image.frombytes("L" if monochrome else "RGB", (width, height), bytes(pixels))


def ease_out(t: float) -> float:
    t = min(1.0, max(0.0, t))
    return 3 * (1 - t) ** 2 * t * (900 / 1024) + 3 * (1 - t) * t * t * (950 / 1024) + t ** 3


def write_assets(repo: Path, images: dict[str, Image.Image]) -> None:
    """Mechanical generation of const A8 resources; no runtime font is needed."""
    lines = ['/* Generated by scripts/render_boot_reveal_preview.py --write-assets.',
             ' * 原项目作者：expert电子实验室；二次开发与适配：一只羊蒸鱼。',
             ' * 保留原项目及第三方资源各自的许可证和版权声明。 */',
             '#include "boot_artwork.h"', '']
    for name, image in images.items():
        pixels = image.tobytes()
        lines.append(f'static const LV_ATTRIBUTE_MEM_ALIGN uint8_t {name}_data[] = {{')
        for offset in range(0, len(pixels), 24):
            lines.append('    ' + ', '.join(f'0x{value:02x}' for value in pixels[offset:offset + 24]) + ',')
        lines.extend(['};', f'const lv_img_dsc_t {name} = {{',
            '    .header.cf = LV_IMG_CF_ALPHA_8BIT,', '    .header.always_zero = 0,',
            f'    .header.w = {image.width},', f'    .header.h = {image.height},',
            f'    .data_size = sizeof({name}_data),', f'    .data = {name}_data,', '};', ''])
    (repo / 'src/boot_artwork.c').write_text('\n'.join(lines), encoding='utf-8')
    print(f'Generated {sum(image.width * image.height for image in images.values())} bytes of const A8 artwork')


def main() -> int:
    repo = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=repo / "deliverables/boot-reveal-python")
    parser.add_argument("--font", type=Path, default=Path("C:/Windows/Fonts/msyhbd.ttc"))
    parser.add_argument("--write-assets", action="store_true", help="Regenerate src/boot_artwork.c from this approved design")
    args = parser.parse_args()
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    source = (repo / "src/main_png.c").read_text(encoding="utf-8-sig")
    portrait = asset(source, "ui_img_game3_png")
    wordmark = asset(source, "Exlink_png", monochrome=False)
    caption_text = "一只羊蒸鱼"
    target_height = wordmark.getbbox()[3] - wordmark.getbbox()[1]
    sizes = range(20, 43)
    size = min(sizes, key=lambda value: abs(
        ImageFont.truetype(str(args.font), value).getbbox(caption_text)[3] -
        ImageFont.truetype(str(args.font), value).getbbox(caption_text)[1] - target_height))
    # Supersample only the new text; do not resize the existing artwork.
    scale = 4
    font = ImageFont.truetype(str(args.font), size * scale)
    bounds = font.getbbox(caption_text)
    glyphs = Image.new("L", (bounds[2] - bounds[0], bounds[3] - bounds[1]), 0)
    ImageDraw.Draw(glyphs).text((-bounds[0], -bounds[1]), caption_text, font=font, fill=255)
    glyphs = glyphs.resize((round(glyphs.width / scale), round(glyphs.height / scale)), Image.Resampling.LANCZOS)
    width, height = glyphs.width + 4, glyphs.height + 4
    caption = Image.new("L", (width, height), 0)
    caption.paste(glyphs, (2, 2))
    if args.write_assets:
        write_assets(repo, {"boot_portrait_white": portrait, "boot_caption_white": caption})
    portrait = portrait.convert("RGB")
    caption = caption.convert("RGB")
    x, y = 12, 150

    def wordmark_top(milliseconds: int) -> int:
        return round(480 + (105 - 480) * ease_out((milliseconds - 200) / 450))

    def render(milliseconds: int) -> Image.Image:
        canvas = Image.new("RGB", (480, 480), (0, 0, 0))
        portrait_x = round(-200 + (17 + 200) * ease_out(milliseconds / 450))
        canvas.paste(portrait, (portrait_x, 12))
        canvas.paste(wordmark, (12, wordmark_top(milliseconds)))
        if milliseconds >= 850:
            if milliseconds < 1350:
                stretched = round(height + (width - height) * ease_out((milliseconds - 850) / 500))
                ImageDraw.Draw(canvas).rectangle((x, y, x + stretched - 1, y + height - 1), fill=(255, 255, 255))
            elif milliseconds < 1450:
                ImageDraw.Draw(canvas).rectangle((x, y, x + width - 1, y + height - 1), fill=(255, 255, 255))
            else:
                revealed = round(width * min(1.0, (milliseconds - 1450) / 700))
                if revealed:
                    canvas.paste(caption.crop((0, 0, revealed, height)), (x, y))
                if revealed < width:
                    ImageDraw.Draw(canvas).rectangle((x + revealed, y, x + width - 1, y + height - 1), fill=(255, 255, 255))
        return canvas

    # Reserve every original wordmark colour, then fill the GIF's remaining
    # palette entries with neutral shades for the A8 portrait/caption edges.
    pixel_data = getattr(wordmark, "get_flattened_data", wordmark.getdata)
    colours = sorted(set(pixel_data()))
    wordmark_indices = {colour: index for index, colour in enumerate(colours)}
    remaining = 256 - len(colours)
    colours.extend((level, level, level) for level in
                   (round(index * 255 / (remaining - 1)) for index in range(remaining)))
    palette = Image.new("P", (1, 1))
    palette.putpalette([channel for colour in colours for channel in colour])
    indexed_wordmark = Image.frombytes(
        "P", wordmark.size, bytes(wordmark_indices[colour] for colour in pixel_data()))
    indexed_wordmark.putpalette(palette.getpalette())
    frames = []
    for milliseconds in range(0, 3600, 40):
        frame = render(milliseconds).quantize(palette=palette, dither=Image.Dither.NONE)
        # Pillow's quantizer may approximate even an exact palette colour.
        # Write the original wordmark indices so its red/white pixels stay exact.
        frame.paste(indexed_wordmark, (12, wordmark_top(milliseconds)))
        frames.append(frame)
    final = render(3600)
    final.save(output / "boot-final.png")
    frames[0].save(output / "boot-animation.gif", save_all=True, append_images=frames[1:],
                   duration=40, disposal=2, optimize=False)  # Play once, then stay on the last frame.
    for name, time in (("square", 850), ("stretched", 1400), ("revealing", 1800)):
        render(time).save(output / (name + ".png"))
    assert final.crop((x, y, x + width, y + height)).tobytes() == caption.tobytes()
    assert not render(840).crop((x, y, x + width, y + height)).getbbox()
    assert render(1400).crop((x, y, x + width, y + height)).getextrema() == ((255, 255),) * 3
    print(f"Python effect preview only; font={font.getname()}, size={size}, caption={width}x{height}")
    print(f"Animation: {output / 'boot-animation.gif'}")
    print(f"Final: {output / 'boot-final.png'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
